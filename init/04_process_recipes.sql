-- process_recipes: processing money-makers, i.e. conversions that cost player time.
--
-- Where item_relations (02) holds instant, mechanical conversions (decants,
-- GE-clerk sets, combines) priced as one-off arbitrage, a process recipe is
-- something a player *does* repeatedly: cut planks, make keels, unbox fish
-- crates, mix potions. Its figure of merit is gp/hr, so each row carries
-- what item_relations can't:
--   * fractional quantities (expected yields: an amulet of chemistry recipe
--     yields 0.7875 potions per action, goggles save 10% of secondaries).
--     item_relations consumers cast qty to bigint, so these must live here;
--   * fee_gp: coins paid per action (NPC fees, Zahur's 200 gp, plank make's
--     sawmill cost). Rune costs are legs, not fees;
--   * actions_per_hour + throughput: 'fixed' (a player-speed rate),
--     'volume_capped' (that rate, but never more than the market trades),
--     'volume_bound' (no player-speed limit; the market's hourly volume is
--     the ceiling), 'unknown' (no rate recorded). The kind records where the
--     player-speed figure came from: every kind is capped by buy limits and
--     market volume, and a consumer must never rank on actions_per_hour alone
--     (06's process_quotes_now applies both caps).
--   * a 'reverse' link is only valid on a reversible item_relations row;
--     the sanity queries in docs/database-setup.md check it.
--
-- A recipe that already exists in item_relations links to it by name with
-- relation_name + relation_direction instead of repeating its legs, so the
-- recipe has one source of truth. Exactly one of (relation_name) or
-- (inputs, outputs) is set.
--
-- Legs are jsonb [{"item_id": int, "qty": number}], per one action. Inputs are
-- bought, outputs sold (taxed). Names/buy limits join from `items` at query
-- time.
--
-- Seeded by 05_process_recipes_seed.sql, which is GENERATED by
-- tools/process-import/import.py from the "Processing Flips" sheet. Skill,
-- quest and unlock requirements are NOT curated for those rows yet.
--
-- Prod apply (manual, on eldo, as the ge-data role so the default-privilege
-- grants to ge-mcp / ge-orchestrator attach; 02+03 must already be applied):
--   psql -h 127.0.0.1 -p 5432 -U ge-data -d ge-data \
--     -f init/04_process_recipes.sql -f init/05_process_recipes_seed.sql

CREATE TABLE IF NOT EXISTS process_recipes (
  recipe_id          serial  PRIMARY KEY,
  name               text    NOT NULL UNIQUE,
  category           text    NOT NULL,
  relation_name      text    REFERENCES item_relations (name) ON UPDATE CASCADE,
  relation_direction text    CHECK (relation_direction IN ('forward', 'reverse')),
  inputs             jsonb,
  outputs            jsonb,
  fee_gp             numeric NOT NULL DEFAULT 0 CHECK (fee_gp >= 0),
  actions_per_hour   numeric CHECK (actions_per_hour > 0),
  throughput         text    NOT NULL
                     CHECK (throughput IN ('fixed', 'volume_capped', 'volume_bound', 'unknown')),
  source             text    NOT NULL,
  notes              text,
  CHECK ((relation_name IS NULL) = (relation_direction IS NULL)),
  -- exactly one source of legs: a link, or both own leg arrays (non-empty)
  CHECK (CASE WHEN relation_name IS NULL
              THEN inputs IS NOT NULL AND outputs IS NOT NULL
               AND jsonb_typeof(inputs) = 'array' AND jsonb_array_length(inputs) > 0
               AND jsonb_typeof(outputs) = 'array' AND jsonb_array_length(outputs) > 0
              ELSE inputs IS NULL AND outputs IS NULL END),
  CHECK ((throughput IN ('fixed', 'volume_capped')) = (actions_per_hour IS NOT NULL))
);
